/**
 * Generates detailed world map SVG path data from the world-atlas TopoJSON
 * (Natural Earth 110m country polygons with real borders).
 *
 * Input : scripts/world-atlas.json (Natural Earth 110m countries TopoJSON)
 * Output: src/lib/worldMap.ts
 *         export const COUNTRY_PATHS: { id: string; name: string; d: string }[]
 *         export const BORDERS_PATH: string          (shared interior borders mesh)
 *         export const MAP_VIEWBOX = "0 0 1000 500"
 *         export const EQUIRECT = { x(lon), y(lat) }  — projection helpers
 *
 * Uses d3-geo's geoEquirectangular (handles the antimeridian correctly, unlike
 * the previous hand-rolled decoder which drew horizontal stripes across Russia
 * and Fiji) and topojson-client's mesh() for clean shared-border rendering.
 *
 * Re-run: npx tsx scripts/gen-world-map.js
 */
const fs = require("fs");
const path = require("path");
const geoEquirectangular = require("d3-geo").geoEquirectangular;
const geoPath = require("d3-geo").geoPath;
const topojson = require("topojson-client");

const SRC = path.join(__dirname, "world-atlas.json");
const OUT = path.join(__dirname, "..", "src", "lib", "worldMap.ts");

const topology = JSON.parse(fs.readFileSync(SRC, "utf8"));

// Fit the whole world (including Antarctica) into a 1000x500 viewBox.
const projection = geoEquirectangular()
  .scale(1000 / (2 * Math.PI))
  .translate([500, 250]);
const pathGen = geoPath(projection);

const countriesObj = topology.objects.countries;

// Convert TopoJSON → GeoJSON FeatureCollection (real coordinates, arcs decoded).
const featureCollection = topojson.feature(topology, countriesObj);

const countries = [];
for (const feature of featureCollection.features) {
  if (!feature.geometry) continue; // entries with null geometry
  const name =
    (feature.properties && (feature.properties.name || feature.properties.NAME)) ||
    `Country ${feature.id ?? "?"}`;
  const d = pathGen(feature);
  if (d && d.length > 20) {
    countries.push({ id: String(feature.id ?? name), name, d });
  }
}

// Shared interior borders as ONE thin mesh path (crisper than per-country strokes).
const borders = topojson.mesh(topology, countriesObj, (a, b) => a !== b);
const bordersPath = pathGen(borders);

// Exterior coastline mesh (drawn slightly stronger for definition).
const coast = topojson.mesh(topology, countriesObj, (a, b) => a === b);
const coastPath = pathGen(coast);

const file = `// AUTO-GENERATED by scripts/gen-world-map.js — do not edit by hand.
// Country polygons: Natural Earth 110m via world-atlas TopoJSON.
// Projection: d3-geo geoEquirectangular fitted to a 1000x500 viewBox.
// d3-geo clips polygons at the antimeridian correctly (no wrap-around stripes).
export interface MapCountry {
  id: string;
  name: string;
  d: string;
}

export const COUNTRY_PATHS: MapCountry[] = [
${countries
  .map((c) => `  { id: "${c.id}", name: ${JSON.stringify(c.name)}, d: ${JSON.stringify(c.d)} },`)
  .join("\n")}
];

/** Shared interior borders (single mesh path). */
export const BORDERS_PATH = ${JSON.stringify(bordersPath)};

/** Coastline / exterior outline mesh. */
export const COAST_PATH = ${JSON.stringify(coastPath)};

export const MAP_VIEWBOX = "0 0 1000 500";

/**
 * Project lon/lat to the map's viewBox coordinates.
 * Inverse of the fitted geoEquirectangular used above:
 *   scale s = 1000 / (2π), center (0°, 0°) at (500, 250)
 *   x = 500 + s * lon·π/180
 *   y = 250 - s * lat·π/180
 */
export const EQUIRECT = {
  x: (lon: number) => 500 + (500 / Math.PI) * (lon * Math.PI) / 180,
  y: (lat: number) => 250 - (500 / Math.PI) * (lat * Math.PI) / 180,
};
`;

fs.writeFileSync(OUT, file);
console.log(
  `Wrote ${OUT}: ${countries.length} countries, borders ${bordersPath.length} chars, coast ${coastPath.length} chars.`
);
